#!/bin/sh
# Virtual Architects installer. Adds the architect kit to the repository you run it in.
#
#   curl -fsSL https://raw.githubusercontent.com/abdulrahmanAlotaibi/virtual-architects/main/public/install.sh | sh                 # add what is missing
#   curl -fsSL https://raw.githubusercontent.com/abdulrahmanAlotaibi/virtual-architects/main/public/install.sh | sh -s -- --update  # also refresh the kit's own files
#
# It never overwrites your files. With --update it refreshes only the kit's own files
# (agents, commands, the skill, templates, tools and the Copilot copies). It never touches
# docs/architecture/project.yaml or any document you wrote.
# Generated by scripts/build-kit.py. Set VA_BASE_URL to install from another copy of the kit.
set -eu

BASE_URL="${VA_BASE_URL:-https://raw.githubusercontent.com/abdulrahmanAlotaibi/virtual-architects/main/public}"
ZIP_URL="$BASE_URL/downloads/virtual-architects-kit.zip"
ZIP_SHA256="c08941916d3cca6c16acc2c51ab68422b052d9af6d2faded0dda6a6388ef71e8"
UPDATE_CMD="curl -fsSL https://raw.githubusercontent.com/abdulrahmanAlotaibi/virtual-architects/main/public/install.sh | sh -s -- --update"
# Printed from here, not read from "$0": piped into sh, the script has no file to read.
usage() {
  cat <<EOF
Virtual Architects installer. Adds the architect kit to the folder you run it in.

Add what is missing:
  curl -fsSL https://raw.githubusercontent.com/abdulrahmanAlotaibi/virtual-architects/main/public/install.sh | sh

Also refresh the kit's own files:
  $UPDATE_CMD

It never overwrites your files. With --update it refreshes only the kit's own files
(agents, commands, the skill, templates, tools and the Copilot copies). It never touches
docs/architecture/project.yaml or any document you wrote.
EOF
}
UPDATE=0
for arg in "$@"; do
  case "$arg" in
    --update) UPDATE=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

say() { printf '%s\n' "$*"; }
fail() { printf 'Error: %s\n' "$*" >&2; exit 1; }

command -v curl >/dev/null 2>&1 || fail "curl is required."
TARGET="$(pwd)"
if command -v git >/dev/null 2>&1 && git rev-parse --show-toplevel >/dev/null 2>&1; then
  TOP="$(git rev-parse --show-toplevel)"
  [ "$TOP" = "$TARGET" ] || say "Note: the repository root is $TOP. Installing into $TARGET, where you ran this."
else
  say "Note: $TARGET is not a git repository. Installing here anyway."
fi

TMP="$(mktemp -d 2>/dev/null || mktemp -d -t va)"
trap 'rm -rf "$TMP"' EXIT INT TERM
say "Downloading the kit from $ZIP_URL"
curl -fsSL "$ZIP_URL" -o "$TMP/kit.zip" || fail "could not download $ZIP_URL"

if command -v sha256sum >/dev/null 2>&1; then GOT="$(sha256sum "$TMP/kit.zip" | cut -d' ' -f1)"
elif command -v shasum >/dev/null 2>&1; then GOT="$(shasum -a 256 "$TMP/kit.zip" | cut -d' ' -f1)"
else GOT=""; say "Note: no sha256sum or shasum found, so the download is not verified."; fi
if [ -n "$GOT" ] && [ "$GOT" != "$ZIP_SHA256" ]; then
  [ -z "${VA_BASE_URL:-}" ] && fail "the download does not match the expected checksum. Nothing was installed."
  say "Note: VA_BASE_URL is set and this kit differs from the published one, so its checksum is not verified."
fi

mkdir -p "$TMP/kit"
if command -v unzip >/dev/null 2>&1; then unzip -q "$TMP/kit.zip" -d "$TMP/kit"
elif command -v python3 >/dev/null 2>&1; then python3 -c 'import sys,zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])' "$TMP/kit.zip" "$TMP/kit"
else fail "unzip or python3 is required to unpack the kit."; fi

# The kit's own files: safe to refresh with --update. Everything else is yours once written.
owned() {
  case "$1" in
    .claude/agents/*|.claude/commands/arch-*|.claude/skills/solution-design/*|.claude/scripts/*) return 0 ;;
    .github/agents/*|.github/skills/arch-*|.github/skills/solution-design/*|.github/prompts/arch-*) return 0 ;;
    .github/workflows/sync-copilot.yml|.github/workflows/architecture-docs.yml) return 0 ;;
    docs/architecture/practice/templates/*|docs/architecture/tools/*) return 0 ;;
    docs/architecture/README.md|docs/architecture/LICENSE|docs/architecture/practice/ea-playbook.md) return 0 ;;
  esac
  return 1
}

added=0; updated=0; same=0; kept=""
cd "$TMP/kit"
for f in $(find . -type f | sed 's|^\./||' | sort); do
  [ "$f" = "INSTALL.md" ] && continue
  dest="$TARGET/$f"
  if [ ! -e "$dest" ]; then
    mkdir -p "$(dirname "$dest")"; cp -p "$f" "$dest"; added=$((added + 1))
  elif cmp -s "$f" "$dest"; then
    same=$((same + 1))
  elif [ "$UPDATE" = 1 ] && owned "$f"; then
    cp -p "$f" "$dest"; updated=$((updated + 1))
  else
    kept="$kept
  $f"
  fi
done

say ""
say "Virtual Architects: $added added, $updated updated, $same already up to date."
if [ -n "$kept" ]; then
  say "Kept your version of:$kept"
  if [ "$UPDATE" != 1 ]; then
    say "To refresh the kit's own files, run it again with --update. Your project.yaml and documents are never replaced:"
    say "  $UPDATE_CMD"
  fi
fi
say ""
say "Next, in Claude Code or Copilot Chat: /arch-profile to describe your project, then ask a"
say "first question, for example /arch-board should we add a second payment provider?"
say "Guide: https://github.com/abdulrahmanAlotaibi/virtual-architects#install-the-team"
